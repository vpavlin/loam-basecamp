// delivery_transport.hpp: the shared receive/send vectors (delivery_vectors.json, also checked by
// loam-transport's TS tests), the node config, and the lifecycle (adopt, nodeStarted, reconnect)
// against fake delivery_module Ops.
//   g++ -std=c++17 -I core/include -I <nlohmann/include> core/test/delivery_transport_test.cpp -o /tmp/dt_test
//   /tmp/dt_test core/test/delivery_vectors.json          (check)
//   /tmp/dt_test --gen > core/test/delivery_vectors.json  (regenerate: only when the wire changes)
#include "loam/delivery_transport.hpp"
#include <nlohmann/json.hpp>
#include <cstdio>
#include <fstream>
#include <map>

using J = nlohmann::json;
using namespace loam::delivery;

static int fails = 0;
static void check(bool c, const std::string &what) { printf("  %s %s\n", c ? "ok  " : "FAIL", what.c_str()); if (!c) ++fails; }

static std::string hex(const std::string &s) {
    static const char *h = "0123456789abcdef";
    std::string o;
    for (unsigned char c : s) { o.push_back(h[c >> 4]); o.push_back(h[c & 15]); }
    return o;
}
static std::string unhex(const std::string &h) {
    std::string o;
    for (size_t i = 0; i + 1 < h.size(); i += 2) o.push_back((char)std::stoi(h.substr(i, 2), nullptr, 16));
    return o;
}
static std::string varint(uint64_t v) { std::string o; while (v >= 0x80) { o.push_back((char)((v & 0x7f) | 0x80)); v >>= 7; } o.push_back((char)v); return o; }
static std::string field(int f, const std::string &v) { return varint((uint64_t)f << 3 | 2) + varint(v.size()) + v; }
static J bytesArray(const std::string &s) { J a = J::array(); for (unsigned char c : s) a.push_back((unsigned)c); return a; }
static std::string urlsafe(std::string s) { for (auto &c : s) { if (c == '+') c = '-'; else if (c == '/') c = '_'; } while (!s.empty() && s.back() == '=') s.pop_back(); return s; }
// A single-segment LIP-243 SegmentMessage, as delivery >= 0.3.0 sends a payload that fits one segment.
static std::string wrapSingle(const std::string &p) {
    std::string o = field(1, loam::segcompat::keccak256(p));
    o += varint(2 << 3 | 0) + varint(p.size()); o += varint(4 << 3 | 0) + varint(1); o += field(7, p);
    return o;
}

static J generate() {
    const std::string sealed = std::string("\x01\xfe\x00 sealed bytes \xff\xfb", 18);
    const std::string topic = "/whisperbox/1/form-abc/proto";
    const std::string enc = b64::encode(sealed);          // the inner layer the sender puts on the wire
    const std::string sds = field(1, "msgid") + field(4, topic) + field(5, enc) + field(7, "sender-7");
    const std::string sdsSeg = field(1, "msgid") + field(4, topic) + field(5, wrapSingle(enc)) + field(7, "sender-7");
    std::string multi = field(1, std::string(32, 'h')) + varint(2 << 3 | 0) + varint(500) + varint(3 << 3 | 0) + varint(1)
                      + varint(4 << 3 | 0) + varint(3) + field(7, "part");
    const std::string sdsMulti = field(1, "msgid") + field(4, topic) + field(5, multi) + field(7, "sender-7");
    J v = J::object();
    v["wire"] = LOAM_DELIVERY_WIRE_VERSION;
    v["note"] = "Generated by core/test/delivery_transport_test.cpp --gen. bytesHex = Frame::bytes. phone: the TS payloadCandidates must offer bytesHex.";
    v["send"] = {{"bytesHex", hex(sealed)}, {"payload", bytesArray(enc)}};
    auto c = [&](const char *name, const std::string &t, const std::string &s, J payload, const char *result,
                 const std::string &etopic, const std::string &esender, const std::string &ebytes, bool phone) {
        J x = {{"name", name}, {"topicArg", t}, {"senderArg", s}, {"payload", payload}, {"result", result}, {"phone", phone}};
        if (std::string(result) == "frame") { x["topic"] = etopic; x["sender"] = esender; x["bytesHex"] = hex(ebytes); }
        return x;
    };
    v["receive"] = J::array({
        c("plain relay, byte array (delivery 0.1.x/0.2.x)", topic, "", bytesArray(enc), "frame", topic, "", sealed, true),
        c("plain relay, string", topic, "", J(enc), "frame", topic, "", sealed, true),
        c("plain relay, {_bytes} URL-safe base64 (delivery >= 0.3.0)", topic, "", J{{"_bytes", urlsafe(b64::encode(enc))}}, "frame", topic, "", sealed, false),
        c("plain relay, {_bytes} standard base64 padded", topic, "", J{{"_bytes", b64::encode(enc)}}, "frame", topic, "", sealed, false),
        c("plain relay, wrapped in {payload}", topic, "", J{{"payload", bytesArray(enc)}}, "frame", topic, "", sealed, false),
        c("SDS frame: topic from f4, sender from f7, content raw", "0xmessagehash", "", J{{"_bytes", urlsafe(b64::encode(sds))}}, "frame", topic, "sender-7", enc, false),
        c("SDS frame in a single-segment SegmentMessage (delivery >= 0.3.0)", "channel", "x", J{{"_bytes", urlsafe(b64::encode(sdsSeg))}}, "frame", topic, "sender-7", enc, false),
        c("SDS frame, part of a multi-segment message", "channel", "x", J{{"_bytes", urlsafe(b64::encode(sdsMulti))}}, "segmented", "", "", "", false),
        c("empty payload", topic, "", J(""), "empty", "", "", "", false),
        c("not base64, not SDS", topic, "", J("***"), "empty", "", "", "", false),
        c("an object without bytes", topic, "", J{{"x", 1}}, "empty", "", "", "", false),
    });
    return v;
}

static void vectors(const J &v) {
    printf("vectors (wire %d)\n", v["wire"].get<int>());
    check(v["wire"].get<int>() == LOAM_DELIVERY_WIRE_VERSION, "vectors are for this wire version");
    check(encodeSend<J>(unhex(v["send"]["bytesHex"].get<std::string>()), 1) == v["send"]["payload"], "send: payload for the sealed bytes");
    for (const auto &x : v["receive"]) {
        Frame f; const Decoded d = decodeReceived<J>(x["topicArg"], x["senderArg"], x["payload"], 7, f);
        const std::string r = x["result"];
        const std::string name = x["name"];
        if (r == "frame") check(d == Decoded::Frame && f.topic == x["topic"] && f.sender == x["sender"] && hex(f.bytes) == x["bytesHex"] && f.ts == 7, name);
        else if (r == "segmented") check(d == Decoded::Segmented, name);
        else check(d == Decoded::Empty, name);
    }
}

static void config() {
    printf("nodeConfig\n");
    J c = nodeConfig<J>(J::object());
    check(c["preset"] == "" && c["clusterId"] == 2 && c["numShardsInNetwork"] == 8 && c["entryNodes"].size() == 6, "default: logos.test without RLN");
    check(c["mode"] == "Core" && c["tcpPort"] == 0 && c["discv5UdpPort"] == 0, "Core, random ports");
    check(nodeConfig<J>(J::object(), true)["preset"] == "logos.test", "rln: the preset name");
    J l = nodeConfig<J>(J{{"preset", "logos.test"}, {"messagingOverrides", {{"discv5-udp-port", 9100}, {"log-level", "INFO"}}}});
    check(!l.contains("messagingOverrides") && l["discv5UdpPort"] == 9100 && l["logLevel"] == "INFO" && l["preset"] == "", "layered shape flattened, preset logos.test made RLN-off");
    J o = nodeConfig<J>(J{{"preset", "logos.dev"}, {"mode", "Edge"}});
    check(o["preset"] == "logos.dev" && o["mode"] == "Edge" && !o.contains("clusterId"), "another preset is left alone");
}

// Fake delivery_module.
struct Fake {
    std::string createErr; bool nodeStartedEvent = true; bool metricsOk = true; long peers = 5;
    std::string conn = "Connected";
    std::vector<std::string> calls, subscribed;
    std::vector<std::pair<std::string, J>> sent;
    std::vector<J::array_t::value_type> dummy;
    std::vector<typename DeliveryTransport<J>::RecvCb> handlers;
    std::function<void(bool, const std::string &)> started;
    typename DeliveryTransport<J>::Ops ops() {
        typename DeliveryTransport<J>::Ops o;
        o.createNode = [this](const std::string &, auto cb) { calls.push_back("createNode"); cb(createErr.empty(), createErr); };
        o.start = [this](auto cb) { calls.push_back("start"); cb(true, ""); if (nodeStartedEvent && started) started(true, ""); };
        o.stop = [this](auto cb) { calls.push_back("stop"); cb(true, ""); };
        o.subscribe = [this](const std::string &t, auto cb) { subscribed.push_back(t); cb(true, ""); };
        o.sendRaw = [this](const std::string &t, const J &p, auto cb) { sent.push_back({t, p}); cb(true, ""); };
        o.onMessage = [this](auto h) { calls.push_back("onMessage"); handlers.push_back(h); };
        o.onNodeStarted = [this](auto cb) { started = cb; };
        o.metrics = [this](auto cb) { calls.push_back("metrics"); cb(metricsOk, "libp2p_peers " + std::to_string(peers) + "\n"); };
        o.connectionStatus = [this](auto cb) { cb(true, conn); };
        return o;
    }
    int count(const std::string &c) const { int n = 0; for (auto &x : calls) n += x == c; return n; }
};

static void lifecycle() {
    printf("lifecycle\n");
    check(DeliveryTransport<J>::isRunning("Connected") && DeliveryTransport<J>::isRunning("PartiallyConnected") &&
          !DeliveryTransport<J>::isRunning("Disconnected") && !DeliveryTransport<J>::isRunning(""), "connection status: running or not");
    const std::string topic = "/app/1/t/proto";
    {   // We create the node.
        Fake d; DeliveryTransport<J>::Config cfg; cfg.nodeConfigJson = "{}";
        DeliveryTransport<J> t(d.ops(), cfg);
        int ready = 0; std::vector<Frame> got; t.onReady = [&] { ++ready; }; t.onFrame = [&](const Frame &f) { got.push_back(f); };
        t.join(topic);
        check(!t.send(topic, "x"), "send before ready is refused");
        t.start();
        check(t.ready() && ready == 1 && !t.adopted(), "created, started, ready on nodeStarted");
        check(d.count("onMessage") == 2, "receive handler registered before createNode and again after ready");
        check(d.subscribed.size() == 1 && d.subscribed[0] == topic, "early join subscribed once ready");
        check(t.send(topic, "hello") && d.sent.size() == 1 && d.sent[0].second == bytesArray(b64::encode("hello")), "send: byte array of base64");
        d.handlers.back()(topic, "", bytesArray(b64::encode("hello")), 1);
        d.handlers.back()("/other/1/x/proto", "", bytesArray(b64::encode("not ours")), 1);
        check(got.size() == 1 && got[0].bytes == "hello", "receives its topic, ignores another app's topic");
        // Peerless watchdog.
        t.notePeers(3, 1000); t.notePeers(0, 2000); t.notePeers(0, 20000);
        check(d.count("stop") == 0, "not peerless long enough yet");
        t.notePeers(0, 33000);
        check(d.count("stop") == 1 && d.count("start") == 2 && t.ready() && ready == 2 && d.subscribed.size() == 2, "peerless 30 s: stop, start, join again, ready again");
    }
    {   // loam_core's settings (as <= 0.7.3): every frame passes, channel handler always registered.
        Fake d; DeliveryTransport<J>::Config cfg; cfg.onlyJoinedTopics = false; cfg.alwaysListenChannels = true;
        auto ops = d.ops(); int chan = 0; ops.onChannelMessage = [&](auto) { ++chan; };
        DeliveryTransport<J> t(ops, cfg);
        std::vector<Frame> got; t.onFrame = [&](const Frame &f) { got.push_back(f); };
        t.start();
        d.handlers.back()("/other/1/x/proto", "", bytesArray(b64::encode("any")), 1);
        check(got.size() == 1 && chan == 2, "loam_core mode: frames on any topic pass, channel handler registered (before and after ready)");
    }
    {   // Another module created the node and runs it: adopt it.
        Fake d; d.createErr = "Context already initialized"; DeliveryTransport<J>::Config cfg;
        DeliveryTransport<J> t(d.ops(), cfg);
        std::vector<std::string> warnings; t.onWarning = [&](const std::string &w) { warnings.push_back(w); };
        t.join(topic); t.start();
        check(t.ready() && t.adopted() && d.count("start") == 0, "adopted a running node (status Connected), did not start it");
        check(!warnings.empty() && warnings[0].find("LOGOS_DELIVERY_RLN_PRESETS") != std::string::npos, "warns that the config is someone else's (RLN hint)");
        check(d.subscribed.size() == 1, "joined its topic on the adopted node");
    }
    {   // Adopted, the owner starts it a bit later (nodeStarted).
        Fake d; d.createErr = "Context already initialized"; d.conn = "Disconnected"; DeliveryTransport<J>::Config cfg;
        DeliveryTransport<J> t(d.ops(), cfg);
        t.start();
        check(!t.ready() && t.status() == "adopting", "adopting a created but not started node (metrics answer, status Disconnected): waiting");
        d.started(true, "");
        check(t.ready() && d.count("start") == 0, "ready when the owner's node starts");
    }
    {   // Adopted, nobody starts it: start it after adoptStartAfterSeconds.
        Fake d; d.createErr = "Context already initialized"; d.conn = "Disconnected"; DeliveryTransport<J>::Config cfg;
        DeliveryTransport<J> t(d.ops(), cfg);
        t.start(); t.tick(1000); t.tick(20000);
        check(!t.ready() && d.count("start") == 0, "not yet");
        t.tick(32000);
        check(t.ready() && d.count("start") == 1, "started it itself after 30 s");
    }
    {   // A real createNode error.
        Fake d; d.createErr = "Invalid JSON config"; DeliveryTransport<J>::Config cfg;
        DeliveryTransport<J> t(d.ops(), cfg);
        std::string err; t.onError = [&](const std::string &e) { err = e; };
        t.start();
        check(!t.ready() && err.find("Invalid JSON") != std::string::npos && t.status().rfind("error", 0) == 0, "createNode error is reported");
    }
}

int main(int argc, char **argv) {
    if (argc > 1 && std::string(argv[1]) == "--gen") { printf("%s\n", generate().dump(2).c_str()); return 0; }
    std::string path = argc > 1 ? argv[1] : "core/test/delivery_vectors.json";
    std::ifstream in(path); if (!in) { printf("no vectors at %s\n", path.c_str()); return 1; }
    J v = J::parse(in);
    vectors(v);
    check(v == generate(), "vectors file matches what this build generates");
    config();
    lifecycle();
    printf(fails ? "DELIVERY TRANSPORT: %d FAILED\n" : "DELIVERY TRANSPORT GREEN\n", fails);
    return fails ? 1 : 0;
}
